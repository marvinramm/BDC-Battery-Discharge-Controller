void DisplayInit() {
  if (!display.begin(SSD1306_SWITCHCAPVCC, DISPLAY_ADRESS)) {
    Serial.println(F("SSD1306 allocation failed"));
  }
  display.clearDisplay();
}

void DrawBootPage() {
  display.clearDisplay();

  display.drawBitmap(0, 0, MojoFPVLOGO_Bitmap, 128, 64, WHITE);

  display.display();
  delay(2000);

  display.clearDisplay();
  

  display.setTextSize(1);
  display.setTextColor(WHITE);
  display.setCursor(0, 0);
  display.println("B Battery");

  display.setTextSize(1);
  display.setTextColor(WHITE);
  display.setCursor(0, 10);
  display.println("D Discharge");

  display.setTextSize(1);
  display.setTextColor(WHITE);
  display.setCursor(0, 20);
  display.println("C Controller");

  display.setTextSize(1);
  display.setTextColor(WHITE);
  display.setCursor(0, 45);
  display.println("Dev. by Marvin Ramm");

  display.setTextSize(1);
  display.setTextColor(WHITE);
  display.setCursor(0, 55);
  display.println("Rev: V0.4");

  display.display();
  delay(2000);
}

void UpdateDisplay() {
  display.clearDisplay();
  display.display();

  if (PageNumber == 0) {  //Main Page
    if (MainPageNumber == 0) {

      if (EnDischarge == true) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 0);
        display.println("Discharge...");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 0);
        display.println("Idle");
      }

      if (current_mA < 100) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 15);
        display.print("I: ");
        display.print(0.00);
        display.println("mA");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 15);
        display.print("I: ");
        display.print(current_mA);
        display.println("mA");
      }

      if (loadVoltage_V < 4) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 25);
        display.print("V: ");
        display.print(0);
        display.println("V");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 25);
        display.print("V: ");
        display.print(loadVoltage_V + 0.7);
        display.println("V");
      }

      if (loadVoltage_V < 4) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 35);
        display.print("P: ");
        display.print(0);
        display.println("W");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 35);
        display.print("P: ");
        display.print((loadVoltage_V + 0.7) * (current_mA / 1000));
        display.println("W");
      }

      display.setTextSize(1);
      display.setTextColor(WHITE);
      display.setCursor(0, 45);
      display.print("Anz: ");
      display.println("N/A");

      display.display();


    } else if (MainPageNumber == 1) {

      if (EnDischarge == true) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 0);
        display.println("Discharge...");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(0, 0);
        display.println("Idle");
      }

      display.setTextSize(1);
      display.setTextColor(WHITE);
      display.setCursor(0, 15);
      display.print("1:");
      display.print(Cell1Average);
      display.print("V");

      display.setTextSize(1);
      display.setTextColor(WHITE);
      display.setCursor(0, 25);
      display.print("2:");
      display.print(Cell2Average);
      display.print("V");

      display.setTextSize(1);
      display.setTextColor(WHITE);
      display.setCursor(0, 35);
      display.print("3:");
      if (DischargeState == 1) {
        display.print(Cell3Average + 0.02);
        display.print("V");
      } else {
        display.print(Cell3Average);
        display.print("V");
      }

      if (Cell4Average < 3.58) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(80, 15);
        display.print("4:");
        display.print("N/A");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(80, 15);
        display.print("4:");
        display.print(Cell4Average);
        display.print("V");
      }

      if (Cell5Average < 3.58) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(80, 25);
        display.print("5:");
        display.print("N/A");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(80, 25);
        display.print("5:");
        display.print(Cell5Average);
        display.print("V");
      }

      if (Cell6Average < 3.58) {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(80, 35);
        display.print("6:");
        display.print("N/A");
      } else {
        display.setTextSize(1);
        display.setTextColor(WHITE);
        display.setCursor(80, 35);
        display.print("6:");
        display.print(Cell6Average);
        display.print("V");
      }


      display.display();
    }
  } else {  //Menu
    if (MenuPageNumber == 0) {

      display.setTextSize(1);
      display.setTextColor(WHITE);
      display.setCursor(0, 15);
      display.print("1:");
      display.print(Cell1);
      display.println("V");
      display.display();

    } else if (MenuPageNumber == 1) {

      display.setTextSize(1);
      display.setTextColor(WHITE);
      display.setCursor(0, 0);
      display.println("1B");
      display.display();
    }
  }
}